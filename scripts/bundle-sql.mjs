#!/usr/bin/env node
/**
 * Concatenates the whole database setup into one paste-able script.
 *
 *   node scripts/bundle-sql.mjs     ->  supabase/all_in_one.sql
 *
 * The output is the exact order the provisioning script applies: migrations
 * 0001..0009, then storage.sql, then the demo register. It exists for the case
 * where a project cannot be driven through the Management API - the Dashboard's
 * SQL editor only accepts one paste comfortably, so everything ships as one
 * file with section banners instead of eleven.
 *
 * all_in_one.sql is generated, never edited by hand: change the source files
 * and re-run this.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DIR = resolve(ROOT, 'supabase');
const OUT = resolve(DIR, 'all_in_one.sql');

const files = [
  ...readdirSync(resolve(DIR, 'migrations')).filter((f) => f.endsWith('.sql')).sort()
    .map((f) => `migrations/${f}`),
  'storage.sql',
  'seed.sql',
];

const parts = [
  `-- ===========================================================================
-- Yash Honda Vacancy & Hiring Tracker - complete database setup, one script
-- GENERATED by scripts/bundle-sql.mjs - edit the sources, not this file.
-- Order: ${files.length} files, migrations then storage then the demo register.
-- Run as the project owner (the Dashboard SQL editor role), once, on an empty
-- project. Re-running is safe: the demo register refuses to double-load.
-- ===========================================================================`,
];

for (const f of files) {
  const path = resolve(DIR, f);
  if (!existsSync(path)) throw new Error(`missing ${f}`);
  const body = readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trimEnd();
  const bar = `-- >>>>>>>>>> ${f} <<<<<<<<<<`;
  const end = `-- <<<<<<<<<< ${f} >>>>>>>>>>`;
  parts.push(`${bar}\n${body}\n${end}\n`);
}

writeFileSync(OUT, `${parts.join('\n')}\n`);
const kb = Math.round(readFileSync(OUT).length / 1024);
process.stdout.write(`wrote supabase/all_in_one.sql (${kb} KB, ${files.length} files)\n`);
